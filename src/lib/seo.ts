import type { Metadata } from 'next';
import { siteConfig } from './site-config';

type OpenGraph = NonNullable<Metadata['openGraph']>;

/**
 * Canonical URL + Open Graph tags for an indexable page. Spread the result
 * into the page's metadata:
 *
 *   export const metadata: Metadata = {
 *     title,
 *     description,
 *     ...pageSeo('/faq', { title, description }),
 *   };
 *
 * Every indexable page sets these itself, because neither inherits well:
 *  - a canonical set in a layout would point every page at the layout's
 *    URL, telling Google to drop them;
 *  - Next replaces (doesn't merge) a layout's `openGraph` when a page sets
 *    one, so og:url, og:image and og:site_name would go missing.
 *
 * `openGraph` overrides the defaults below (pass `images` to use a photo
 * instead of the generated site card).
 */
export function pageSeo(
  path: string,
  openGraph: OpenGraph,
): Pick<Metadata, 'alternates' | 'openGraph'> {
  const url = path === '/' ? siteConfig.url : `${siteConfig.url}${path}`;
  return {
    alternates: { canonical: url },
    openGraph: {
      type: 'website',
      locale: 'en_US',
      siteName: siteConfig.name,
      // The card generated by src/app/opengraph-image.tsx.
      images: [
        {
          url: '/opengraph-image',
          width: 1200,
          height: 630,
          alt: `${siteConfig.name} — Swim with wild manatees`,
        },
      ],
      ...openGraph,
      url,
    },
  };
}
