import type { Metadata } from 'next';
import { publicContactEmail, siteConfig } from './site-config';
import { formatPrice } from './tours';
import type { PriceRange } from './pricing';

type OpenGraph = NonNullable<Metadata['openGraph']>;

/**
 * Canonical URL + Open Graph tags for an indexable page. Spread the result
 * into the page's metadata:
 *
 *   export const metadata: Metadata = {
 *     title,
 *     description,
 *     ...pageSeo('/faq', { title, description }),
 *   };
 *
 * Every indexable page sets these itself, because neither inherits well:
 *  - a canonical set in a layout would point every page at the layout's
 *    URL, telling Google to drop them;
 *  - Next replaces (doesn't merge) a layout's `openGraph` when a page sets
 *    one, so og:url, og:image and og:site_name would go missing.
 *
 * `openGraph` overrides the defaults below (pass `images` to use a photo
 * instead of the generated site card).
 */
export function pageSeo(
  path: string,
  openGraph: OpenGraph,
): Pick<Metadata, 'alternates' | 'openGraph'> {
  const url = path === '/' ? siteConfig.url : `${siteConfig.url}${path}`;
  return {
    alternates: { canonical: url },
    openGraph: {
      type: 'website',
      locale: 'en_US',
      siteName: siteConfig.name,
      // The card generated by src/app/opengraph-image.tsx.
      images: [
        {
          url: '/opengraph-image',
          width: 1200,
          height: 630,
          alt: `${siteConfig.name} — Swim with wild manatees`,
        },
      ],
      ...openGraph,
      url,
    },
  };
}

/**
 * Schema.org node for the business itself, used on the homepage and
 * /contact. (It replaces a `TouristAttraction` node, which describes a
 * place to visit rather than the company running the tours.)
 *
 * Don't add `aggregateRating` or `Review` here built from the site's own
 * testimonials: Google treats self-collected reviews as ineligible for star
 * snippets and can penalize them. Reviews belong on the Google Business
 * Profile.
 */
export function localBusinessJsonLd(prices: PriceRange | null) {
  const email = publicContactEmail();
  const profiles: (string | null)[] = [
    siteConfig.captain.instagram,
    siteConfig.captain.facebook,
    siteConfig.googleBusinessProfile,
  ];
  return {
    '@context': 'https://schema.org',
    '@type': 'TravelAgency',
    '@id': `${siteConfig.url}/#business`,
    name: siteConfig.name,
    description:
      'Small-group, family-friendly snorkel-with-manatee tours on the Crystal River with USCG-licensed Captain Travis Urbin.',
    url: siteConfig.url,
    telephone: siteConfig.contact.phoneHref.replace('tel:', ''),
    ...(email && { email }),
    image: `${siteConfig.url}/opengraph-image`,
    // The manatee mark, 180×180 (src/app/apple-icon.tsx).
    logo: `${siteConfig.url}/apple-icon`,
    ...(prices && {
      priceRange:
        prices.min === prices.max
          ? formatPrice(prices.min)
          : `${formatPrice(prices.min)}–${formatPrice(prices.max)}`,
    }),
    address: {
      '@type': 'PostalAddress',
      streetAddress: siteConfig.marina.streetAddress,
      addressLocality: siteConfig.marina.city,
      addressRegion: siteConfig.marina.region,
      postalCode: siteConfig.marina.postalCode,
      addressCountry: siteConfig.marina.country,
    },
    geo: {
      '@type': 'GeoCoordinates',
      latitude: siteConfig.marina.latitude,
      longitude: siteConfig.marina.longitude,
    },
    sameAs: profiles.filter((u): u is string => !!u),
  };
}
